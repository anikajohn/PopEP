#!/usr/bin/env bash
# Run PopEP raw_read_extraction and then THD_calculations on the simulated samples.
# Usage:  conda activate popep_raw && bash pipeline_test/run_both_workflows.sh <path/to/PopEP> [cores]
#
# THD_calculations calls conda envs by name (`conda run -n nextclade|THD_analysis`).
# Test copies of those envs live in POPEP_TEST_ENVS (built from pipeline_test/environment_*.yaml)
# and are put first on CONDA_ENVS_PATH, so envs with the same name elsewhere are not used or changed.
# THD settings match PopEP's THD_calculations/workflow_rawReads/config/haplo_H1_24_25/config.yaml.
set -euo pipefail
ME="$(cd "$(dirname "$0")/.." && pwd)"
POPEP="$(cd "$1" && pwd)"
CORES="${2:-8}"
POPEP_TEST_ENVS="${POPEP_TEST_ENVS:-$HOME/miniconda3/envs_popep_test}"
export CONDA_ENVS_PATH="$POPEP_TEST_ENVS${CONDA_ENVS_PATH:+:$CONDA_ENVS_PATH}"

# 1) raw_read_extraction
bash "$ME/pipeline_test/run_raw_read_extraction.sh" "$POPEP" "$CORES"

# 2) THD_calculations
WF="$POPEP/THD_calculations/workflow_rawReads"
OUT="$ME/results/pipeline/THD_calculations"
CFG="$ME/pipeline_test/config_THD_calculations.yaml"
cat > "$CFG" <<EOF
# generated by run_both_workflows.sh
input_dir: "$ME/results/pipeline/raw_read_extraction"
output_dir: "$OUT"
reference: "$ME/resources/reference/H1.fasta"
reference_dataset: "$WF/resources/datasets/H1_26update/CY121680"
colour_palette: "$WF/resources/colour_palette/H1/colours.json"
mutation_rate: 0.00329
timescales: "0.15,0.2,0.25,0.3,0.35,0.4"
timewindows: "0.019,0.038,0.0833,0.15,0.23"
nextclade_subclade_col: "subclade"
nextclade_clade_col: "legacy-clade"
amplicons:
  amplicon2: {}
  amplicon3: {}
  amplicon4: {}
  amplicon5: {}
  amplicon6: {}
locations:
  zurich: {location_name: "Zürich (ZH)", location_code: "10"}
  lugano: {location_name: "Lugano (TI)", location_code: "05"}
EOF

for env in nextclade THD_analysis; do
    [ -d "$POPEP_TEST_ENVS/$env" ] || { echo "missing env $POPEP_TEST_ENVS/$env (conda env create -p ... -f pipeline_test/environment_$env.yaml)"; exit 1; }
done

snakemake -s "$WF/Snakefile" -d "$WF" --configfile "$CFG" --cores "$CORES" \
    --rerun-incomplete --show-failed-logs
