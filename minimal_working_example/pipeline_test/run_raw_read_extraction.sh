#!/usr/bin/env bash
# Run PopEP raw_read_extraction on the simulated samples.
# Usage:  conda activate popep_raw && bash pipeline_test/run_raw_read_extraction.sh <path/to/PopEP> [cores]
# Thresholds match PopEP's raw_read_extraction/workflow/config/H1_24_25/config.yaml (haplotype_dev).
set -euo pipefail
ME="$(cd "$(dirname "$0")/.." && pwd)"
POPEP="$(cd "$1" && pwd)"
CORES="${2:-8}"
WF="$POPEP/raw_read_extraction/workflow"
OUT="$ME/results/pipeline/raw_read_extraction"
CFG="$ME/pipeline_test/config_raw_read_extraction.yaml"

samtools faidx "$ME/resources/reference/H1.fasta"

cat > "$CFG" <<EOF
# generated by run_raw_read_extraction.sh
path_to_data: "$ME/data/samples"
# prep_samples_yaml.py keeps dates strictly between these, so pad by one day
time_start: "2024-10-31"
time_end: "2025-04-02"
reference: "$ME/resources/reference/H1.fasta"
reference_name: "CY121680.1"
reference_index: "$ME/resources/reference/H1.fasta.fai"
output_dir: "$OUT"
minimal_read_length: 200
minimal_read_mapping_quality: 9
threshold_value: 0.000000000000001
rare_mutation_limit_days: 1
coverage_threshold: 1
phred_score_threshold: 5
amplicons:
  amplicon2: {bedfile: "$ME/resources/amplicons/H1.amp2.insert.empirical.bed"}
  amplicon3: {bedfile: "$ME/resources/amplicons/H1.amp3.insert.bed"}
  amplicon4: {bedfile: "$ME/resources/amplicons/H1.amp4.insert.bed"}
  amplicon5: {bedfile: "$ME/resources/amplicons/H1.amp5.insert.bed"}
  amplicon6: {bedfile: "$ME/resources/amplicons/H1.amp6.insert.bed"}
locations:
  zurich: {location_name: "Zürich (ZH)", location_code: "10"}
  lugano: {location_name: "Lugano (TI)", location_code: "05"}
EOF

snakemake -s "$WF/Snakefile" -d "$WF" --configfile "$CFG" --cores "$CORES" \
    --rerun-incomplete --show-failed-logs
